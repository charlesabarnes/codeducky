//! Where a terminal's bytes come from, shaped after herdr-core's `terminal.attach` stream.
//!
//! One attach is one stream: the view calls [`TerminalSource::attach`] with the measured grid,
//! gets a fresh event channel, and feeds a fresh emulator from it. Calling `attach` again
//! detaches the old stream and replays the program's screen (and `history` lines) on the new one.

mod loopback;
#[cfg(feature = "pty")]
mod pty;

pub use loopback::{LoopbackHandle, LoopbackSource};
#[cfg(feature = "pty")]
pub use pty::{LocalPtySource, PtyCommand};

use crate::color::Rgb;

/// A grid size in cells plus the pixel size of one cell.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct GridSize {
    pub cols: u16,
    pub rows: u16,
    pub cell_width: u32,
    pub cell_height: u32,
}

/// What the program is told about our display (hc `Display` / FACTS): it answers OSC 10/11/12
/// colour queries and CSI 14/16/18 t size queries with these.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DisplayFacts {
    pub foreground: Rgb,
    pub background: Rgb,
    pub cursor: Rgb,
    pub cell_width: u32,
    pub cell_height: u32,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct AttachRequest {
    pub size: GridSize,
    /// Scrollback lines to replay before the screen (main screen only).
    pub history: usize,
    pub display: DisplayFacts,
}

/// Viewer to program.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ViewerMessage {
    /// Keys and pastes typed by the user.
    Input(Vec<u8>),
    /// Replies generated by our emulator (hc AUTOMATIC_INPUT); not human activity.
    AutomaticInput(Vec<u8>),
    Resize(GridSize),
    /// `report` is the focus-event sequence when the program enabled mode 1004. A source whose
    /// far end tracks modes itself (hc) ignores it; a raw PTY writes it.
    Focus {
        focused: bool,
        report: Option<Vec<u8>>,
    },
    Display(DisplayFacts),
    Detach,
}

/// Program to viewer, on the channel returned by [`TerminalSource::attach`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum SourceEvent {
    Output(Vec<u8>),
    /// Another viewer became active and the program now runs at this size.
    SizeChanged {
        cols: u16,
        rows: u16,
    },
    /// The source wants a fresh attach (for example after the terminal restarted).
    ReattachRequested,
    Closed(CloseReason),
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum CloseReason {
    Exited { code: Option<i32> },
    Lost(String),
    Detached,
}

#[derive(Debug, thiserror::Error)]
pub enum SourceError {
    #[error("attach failed: {0}")]
    Attach(String),
    #[error(transparent)]
    Io(#[from] std::io::Error),
}

pub trait TerminalSource: 'static {
    /// Starts a new stream at `request.size`, detaching any previous one. The first output on
    /// the new stream is a full repaint, so the caller must feed it to a fresh emulator.
    fn attach(
        &mut self,
        request: &AttachRequest,
    ) -> Result<flume::Receiver<SourceEvent>, SourceError>;

    /// Must not block on the far end; implementations queue or write without waiting for replies.
    fn send(&mut self, message: ViewerMessage);
}
